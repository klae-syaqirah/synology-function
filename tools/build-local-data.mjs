// Rebuilds the offline copy the site falls back to from a folder of CSV files.
//
// Usage:
//   node tools/build-local-data.mjs                                  data/csv -> data/local-data.js (public site)
//   node tools/build-local-data.mjs private/csv private/local-data.js   internal copy with NAS status (never commit)
//
// To refresh from the Google Sheet: File > Download > Comma-separated values for each tab,
// save as <folder>/<tab>.csv (settings, apps, departments, tasks, glossary, faq), then run this script.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CSV = createRequire(import.meta.url)(join(root, 'assets', 'js', 'csv.js'));

const csvDir = resolve(root, process.argv[2] || join('data', 'csv'));
const outFile = resolve(root, process.argv[3] || join('data', 'local-data.js'));

const TABS = ['settings', 'apps', 'departments', 'tasks', 'glossary', 'faq'];
const out = {};

for (const tab of TABS) {
  const file = join(csvDir, `${tab}.csv`);
  if (!existsSync(file)) {
    console.warn(`skip  ${tab}: ${file} not found`);
    continue;
  }
  const text = readFileSync(file, 'utf8').replace(/^﻿/, '');
  out[tab] = text;
  console.log(`ok    ${tab}: ${CSV.parseObjects(text).length} rows`);
}

const js =
  '// Offline copy of the Google Sheet, used when the sheet is not connected or cannot be reached.\n' +
  '// Generated by tools/build-local-data.mjs from CSV files - edit the CSVs (or the sheet), not this file.\n' +
  `window.LOCAL_CSV = ${JSON.stringify(out, null, 2)};\n`;

writeFileSync(outFile, js);
console.log(`wrote ${outFile}`);
